package com.sahyatri.guide.entity;

/** The two safety pledges an admin records from a guide's onboarding (§7.21.3), in the order the page lists them. */
public enum PledgeKind {
    /** No alcohol or intoxicants from departure until the group is back at base. Shows "Agreed". */
    NO_ALCOHOL,
    /** No serious injuries or evacuations on any trek they have led. Shows "Declared". */
    NO_SERIOUS_INCIDENTS
}
